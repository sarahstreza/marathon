//! Writes the JSON of every [`Action`] and [`Event`] example to
//! `tests/fixtures/control.json`, and fails if the committed file is stale.
//!
//! Other implementations of the control plane use the fixture to prove
//! they speak the same JSON: the Android client (docs/ANDROID.md) decodes
//! and re-encodes every entry. Regenerate it after changing `Action` or
//! `Event` with:
//!
//! ```text
//! UPDATE_FIXTURES=1 cargo test -p marathon-api --test control_fixtures
//! ```
//!
//! (`scripts/gen-android-api.sh` does this too.)

// Test code: panicking on I/O or serialization failure is the right failure.
#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::path::Path;

use marathon_api::{Action, Event};
use serde_json::{Value, json};

fn fixture() -> String {
    let actions: Vec<Value> = Action::examples()
        .iter()
        .map(|a| serde_json::to_value(a).unwrap())
        .collect();
    let events: Vec<Value> = Event::examples()
        .iter()
        .map(|e| serde_json::to_value(e).unwrap())
        .collect();
    let doc = json!({
        "_comment": "Generated by crates/marathon-api/tests/control_fixtures.rs; do not edit.",
        "actions": actions,
        "events": events,
    });
    let mut text = serde_json::to_string_pretty(&doc).unwrap();
    text.push('\n');
    text
}

#[test]
fn control_fixture_is_up_to_date() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/control.json");
    let want = fixture();
    if std::env::var_os("UPDATE_FIXTURES").is_some() {
        std::fs::write(&path, &want).unwrap();
        return;
    }
    // Compare as JSON, not text: whether serde_json keeps keys in order
    // depends on features other workspace crates turn on, so the same
    // values can print in a different key order under `cargo test -p` and
    // `cargo test --workspace`.
    let have: Option<Value> = std::fs::read_to_string(&path)
        .ok()
        .and_then(|text| serde_json::from_str(&text).ok());
    let want: Value = serde_json::from_str(&want).unwrap();
    assert!(
        have.as_ref() == Some(&want),
        "{} is stale. Regenerate it with:\n  UPDATE_FIXTURES=1 cargo test -p marathon-api --test control_fixtures",
        path.display()
    );
}
